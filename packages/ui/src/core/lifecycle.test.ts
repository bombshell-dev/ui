import { describe, expect, test } from 'vitest';
import { create, destroy, id, LifecycleApi } from './lifecycle.ts';
import type { Node } from './node.ts';

describe('lifecycle', () => {
	describe('create', () => {
		test('with no parent, roots the node in the global scope', () => {
			const node = create();
			expect(node.parent).toBeDefined();
		});

		test('wires the child into its parent', () => {
			const parent = create();
			const child = create(parent);
			expect(child.parent).toBe(parent);
			expect(parent.children.has(child)).toBe(true);
		});

		test('autogenerates an id', () => {
			const node = create();
			expect(typeof id(node)).toBe('string');
			expect(id(node).length).toBeGreaterThan(0);
		});

		test('autogenerated ids are distinct', () => {
			expect(id(create())).not.toBe(id(create()));
		});

		test('a child owns its id rather than inheriting its parent’s', () => {
			const parent = create();
			const child = create(parent);
			expect(id(child)).not.toBe(id(parent));
		});

		test('hooks fire through create middleware', () => {
			const created: Node[] = [];
			const root = create();
			LifecycleApi.around(root, {
				create: (args, next) => {
					const node = next(...args);
					created.push(node);
					return node;
				},
			});
			const a = create(root);
			const b = create(a);
			expect(created).toEqual([a, b]);
		});
	});

	describe('destroy', () => {
		test('detaches a node from its parent', () => {
			const parent = create();
			const child = create(parent);
			destroy(child);
			expect(parent.children.has(child)).toBe(false);
		});

		test('cascades to descendants', () => {
			const root = create();
			const parent = create(root);
			const child = create(parent);
			destroy(root);
			expect(root.children.has(parent)).toBe(false);
			expect(parent.children.has(child)).toBe(false);
		});

		test('tears down bottom-up, each node running its destroy middleware', () => {
			const order: Node[] = [];
			const root = create();
			LifecycleApi.around(root, {
				destroy: (args, next) => {
					const result = next(...args);
					order.push(args[0]);
					return result;
				},
			});
			const parent = create(root);
			const child = create(parent);
			destroy(root);
			expect(order).toEqual([child, parent, root]);
		});
	});
});
