import { describe, expect, test } from 'vitest';
import { lifecycle, LifecycleApi } from './lifecycle.ts';
import type { Node } from './node.ts';

describe('lifecycle', () => {
	describe('create', () => {
		test('with no parent, roots the node in the global scope', () => {
			const node = lifecycle.create();
			expect(node.parent).toBeDefined();
		});

		test('wires the child into its parent', () => {
			const parent = lifecycle.create();
			const child = lifecycle.create(parent);
			expect(child.parent).toBe(parent);
			expect(parent.children.has(child)).toBe(true);
		});

		test('autogenerates an id', () => {
			const node = lifecycle.create();
			expect(typeof lifecycle.id(node)).toBe('string');
			expect(lifecycle.id(node).length).toBeGreaterThan(0);
		});

		test('autogenerated ids are distinct', () => {
			expect(lifecycle.id(lifecycle.create())).not.toBe(lifecycle.id(lifecycle.create()));
		});

		test('a child owns its id rather than inheriting its parent’s', () => {
			const parent = lifecycle.create();
			const child = lifecycle.create(parent);
			expect(lifecycle.id(child)).not.toBe(lifecycle.id(parent));
		});

		test('hooks fire through create middleware', () => {
			const created: Node[] = [];
			const root = lifecycle.create();
			LifecycleApi.decorate(root, () => ({
				create(parent) {
					const node = super.create(parent);
					created.push(node);
					return node;
				},
			}));
			const a = LifecycleApi.at(root).create(root);
			const b = LifecycleApi.at(a).create(a);
			expect(created).toEqual([a, b]);
		});
	});

	describe('destroy', () => {
		test('detaches a node from its parent', () => {
			const parent = lifecycle.create();
			const child = lifecycle.create(parent);
			lifecycle.destroy(child);
			expect(parent.children.has(child)).toBe(false);
		});

		test('cascades to descendants', () => {
			const root = lifecycle.create();
			const parent = lifecycle.create(root);
			const child = lifecycle.create(parent);
			lifecycle.destroy(root);
			expect(root.children.has(parent)).toBe(false);
			expect(parent.children.has(child)).toBe(false);
		});

		test('tears down bottom-up, each node running its destroy middleware', () => {
			const order: Node[] = [];
			const root = lifecycle.create();
			LifecycleApi.decorate(root, () => ({
				destroy(node) {
					const result = super.destroy(node);
					order.push(node);
					return result;
				},
			}));
			const parent = lifecycle.create(root);
			const child = lifecycle.create(parent);
			LifecycleApi.at(root).destroy(root);
			expect(order).toEqual([child, parent, root]);
		});
	});
});
